"""
# Yamaha SY77 adaptation.

Adaptation created by github.com/hmmbug.

- Requires synth to be in program change "direct" mode (Utility -> MIDI -> Program Change = direct)
- Requires "Bulk Protect" set to "off" (Utility -> MIDI -> Channel Set -> Bulk Protect = Off)
- The SY77/TG77 has different settings for MIDI Channel and SysEx Device ID.
"""

from enum import IntEnum
import logging
import sys
from types import ModuleType
from typing import List

import testing

logging.basicConfig(level=logging.DEBUG)

from yamaha.Yamaha_SY_TG_common import (
    SYSEX_START,
    YAMAHA_ID,
    SYSEX_END,
)
from Yamaha_SY77 import (
    YamahaSY77,
    MemoryType,
    HELP_STRING,
    BANKS,
)

this_module = sys.modules[__name__]

class YamahaTG77(YamahaSY77):
    # No changes in the subclass, but it'll be easier on the eye in logs
    # having the correct synth name when the class is referenced!
    pass


synth = YamahaTG77(
    synth_name="Yamaha TG77",
    synth_id=0x7a,

    # voice
    first_preset_name="SP|Cosmo  ",
    msg_id_voice_dump="LM  8101VC",
    voice_default_name="INIT VOICE",
    voice_name_length=10,
    offset_voice_name=33,

    # banks
    memory_types=MemoryType,
    banks=BANKS,

    # data offsets in voice bulk dumps
    offset_memory_type=30,          # location of memory type (eg. INT, Preset)
    offset_memory_number=31,        # location of memory number (eg. patch num.)
    offset_req_memory_type=28,      # location of memory type in request
    offset_req_memory_number=29,    # location of memory num. in request

    help_string=HELP_STRING,
)
synth.install(this_module)

