this_module = sys.modules[__name__]


HELP_STRING = \
"""TG33 Systems Settings:
- Set 'Program Change' mode to 'direct'
- Set 'Bulk Protect' to 'off'
- Set 'SysEx Device ID' appropriately. If in doubt, set it the same as the
  MIDI channel or 'omni'.
- Bank downloads are supported but not uploads
- Only supports voice uploads to edit buffer

Only Voices are supported, no Multi, sequencer or other capabilities.
"""

class MemoryType(IntEnum):
    INTERNAL = 0x00
    PRESET1  = 0x02
    PRESET2  = 0x03
    EDIT     = 0x7F

BANKS = [
    { "bank": 0, "name": "Internal", "size": 64, "type": "Voice", "isROM": False, },
    { "bank": 1, "name": "Preset1",  "size": 64, "type": "Voice", "isROM": True,  },
    { "bank": 2, "name": "Preset2",  "size": 64, "type": "Voice", "isROM": True,  },
]

class YamahaTG33(YamahaSY22):
    # TG33 can load SY22 dumps (although this could be confused with SY35 too)
    msg_id_alt_voice_dump="PK  2203AE"
    msg_id_alt_bulk_dump="PK  2203VM"

    def _validateVoiceMessage(self, buf: List[int]) -> bool:
        rtn = (
            self._validateMessage(buf) and
            (
                # accept either TG33 or SY22 voice files.
                # This might get confused with SY35 also.
                self._getMessageType(buf) == str2bytes(self.msg_id_voice_dump) or
                self._getMessageType(buf) == str2bytes(self.msg_id_alt_voice_dump)
            )
        )
        logging.debug(f"validate_voice_message: rtn:{rtn}")
        return rtn


synth = YamahaTG33(
    synth_name="Yamaha TG33",
    synth_id=0x7e,

    # voice
    first_preset_name="SP*Pro33",
    msg_id_voice_dump="LM  0012VE",
    msg_id_all_voice_dump="LM  0012VC",
    voice_default_name="Initial ",
    voice_name_length=8,
    offset_voice_name=28,  # SysEx format differs slightly from SY22/SY35

    # banks
    memory_types=MemoryType,
    banks=BANKS,

    # data offsets in voice bulk dumps
    offset_memory_type=30,          # location of memory type (eg. INT, Preset)
    offset_memory_number=31,        # location of memory number (eg. patch num.)
    offset_req_memory_type=28,      # location of memory type in request
    offset_req_memory_number=29,    # location of memory num. in request

    # misc
    help_string=HELP_STRING,
)
synth.install(this_module)


