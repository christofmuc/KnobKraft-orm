this_module = sys.modules[__name__]


HELP_STRING = """SY35 Systems Settings:
- Set 'Program Change' mode to 'direct'
- Set 'Bulk Protect' to 'off'
- Set 'SysEx Device ID' appropriately. If in doubt, set it the same as the
  MIDI channel or 'omni'.
- Bank downloads are supported but not uploads
- Only supports voice uploads to edit buffer

Only Voices are supported, no Multi, sequencer or other capabilities.
"""


class MemoryType(IntEnum):
    INTERNAL = 0x00
    PRESET = 0x02
    EDIT = 0x7F


BANKS = [
    {
        "bank": 0,
        "name": "Internal",
        "size": 64,
        "type": "Voice",
        "isROM": False,
    },
    {
        "bank": 1,
        "name": "Preset",
        "size": 64,
        "type": "Voice",
        "isROM": True,
    },
]


class YamahaSY35(YamahaSY22):
    pass


synth = YamahaSY35(
    synth_name="Yamaha SY35",
    synth_id=0x7E,
    # voice
    first_preset_name="AP:Rock ",  # Space padded to 8 characters
    msg_id_voice_dump="PK  2203AE",
    msg_id_all_voice_dump="PK  2203VM",
    voice_default_name="Initial ",
    voice_name_length=8,
    offset_voice_name=19,
    # banks
    memory_types=MemoryType,
    banks=BANKS,
    # data offsets in voice bulk dumps
    offset_memory_type=-1,  # location of memory type (eg. INT, Preset)
    offset_memory_number=-1,  # location of memory number (eg. patch num.)
    offset_req_memory_type=-1,  # location of memory type in request
    offset_req_memory_number=-1,  # location of memory num. in request
    # misc
    help_string=HELP_STRING,
)
synth.install(this_module)


