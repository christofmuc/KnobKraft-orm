"""
# Yamaha SY35 adaptations.

Adaptation created by github.com/hmmbug.

## 1 Voice SysEx Format

    01      0xf0 Start SysEx
    02      0x43 Yamaha ID
    03      0x00 Device ID (zero indexed 0-15 -> 1-16)
    04      0x7e Synth ID
    05      0xnn Byte Count MSB
    06      0xnn Byte Count LSB
    07-16   ---- "PK  2203AE"
    17-19   0x?? Unknown
    20-27   Voice name
    ...
"""

